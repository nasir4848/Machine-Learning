"""**uses of Groupby() **"""

data={
    "Dept":["CSE","EEE","CSE","EEE"],
    "Name":["a","b","c","d"],
    "Marks":[80,30,40,50]
}

df=pd.DataFrame(data)
print(df.groupby("Dept")["Marks"].mean())

"""**Value Counts**"""

data={
    "Dept":["CSE","EEE","CSE","EEE","CE"],
    "Name":["a","b","c","d","e"],
    "Marks":[80,30,40,50,70]
}

df=pd.DataFrame(data)
print(df["Dept"].value_counts())

"""**Searching Duplicates**"""

data={
    "Dept":["CSE","EEE","CSE","EEE","CE"],

    "Marks":[80,30,40,50,70]
}

df=pd.DataFrame(data)
print(df.duplicated(subset="Dept"))

df=df.drop_duplicates(subset="Dept")
print(df)

